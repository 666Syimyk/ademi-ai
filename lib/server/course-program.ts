/** Returns true only for questions that explicitly concern the course corpus. */
export function matchesCourseProgramIntent(input: string): boolean {
  const normalized = input.normalize("NFKC").toLocaleLowerCase("und").trim();
  return (
    normalized.length > 0 &&
    courseIntentPatterns.some((pattern) => pattern.test(normalized))
  );
}
